"""
4.3_viscosity_sensitivity.py
============================

Section 4.3: shock-capture and viscosity-sensitivity analysis.

Goal
----
Quantify how the FNO accuracy degrades as the viscosity nu decreases (the
solutions develop sharper shocks), exposing the shock-capturing bottleneck
of a Fourier-based surrogate model.

Procedure
---------
  1. Three datasets with the SAME 1000 GRF initial conditions (Section 4.1.1)
     are used:  nu in {0.1, 0.01, 0.001}.
     - nu = 0.01 : reference solutions from Section 4.1.1,
     - nu = 0.1 and nu = 0.001 : computed by 4.3_generate_reference_solutions.py
       (validated against the Cole-Hopf exact solution).
  2. Train one FNO (L = 4, k_max = 16, d_v = 64) per viscosity on the 800
     training samples at N = 64 with identical hyper-parameters; the
     nu = 0.01 model is reused from Section 4.2.
  3. FDM baselines (Lax-Friedrichs + TVD, N = 64) are computed for nu = 0.1
     and nu = 0.001 (reusing the Section 4.1 FDM solver); the nu = 0.01 FDM
     baseline is reused from Section 4.1.3.
  4. Test-set evaluation (200 samples, N = 64): mean rel L2 / rel Linf with
     bootstrap 95% CI, per-sample errors, and the FNO-to-FDM error ratio.
  5. For nu = 0.001, snapshots of typical samples show the smoothing /
     Gibbs-type behaviour of the FNO at the shocks.

Outputs (all with the "4.3" prefix):
    data/4.3_error_metrics.csv
    data/4.3_summary.csv
    data/4.3_parameters.csv
    data/4.3_fno_nu0p1_weights.pt , data/4.3_fno_nu0p001_weights.pt
    figures/4.3_viscosity_sensitivity.png
    figures/4.3_shock_snapshots.png
    4.3_README.md

All comments and figure labels are in English.
"""

