def main():
    t_start = time.time()
    os.makedirs(DATA_DIR, exist_ok=True)
    os.makedirs(FIG_DIR, exist_ok=True)

    print("=" * 78)
    print("Section 4.3 - shock capture and viscosity sensitivity")
    print("=" * 78)

    u0_all, refs, train_idx, test_idx = load_all_data()
    u0_test = u0_all[test_idx]
    print(f"Data: nu = {NUS}, 800 train / 200 test, N_REF = {N_REF}")

    # ---------- FNO models ----------------------------------------------------
    fnos = {}
    fno = FNO1d()
    fno.load_state_dict(torch.load(os.path.join(DATA_DIR, "4.2_fno_weights.pt")))
    fnos[0.01] = fno
    print("Reused the nu = 0.01 FNO from Section 4.2.")

    step = N_REF // N_GRID
    X_tr = torch.tensor(u0_all[train_idx][:, ::step], dtype=torch.float32)
    for nu in (0.1, 0.001):
        tag = "nu0p1" if nu == 0.1 else "nu0p001"
        wpath = os.path.join(DATA_DIR, f"4.3_fno_{tag}_weights.pt")
        if os.path.exists(wpath):
            model = FNO1d()
            model.load_state_dict(torch.load(wpath))
            print(f"Loaded FNO nu = {nu:g} from {wpath} (resume mode).")
        else:
            Y_tr = torch.tensor(refs[nu][train_idx][:, ::step],
                                dtype=torch.float32)
            model = FNO1d()
            print(f"Training FNO at nu = {nu:g} ...")
            train_model(model, X_tr, Y_tr, name=f"FNO nu={nu:g}")
            torch.save(model.state_dict(), wpath)
        fnos[nu] = model

    # ---------- FNO evaluation at N = 64 --------------------------------------
    print("FNO evaluation on the 200 test samples (N = 64) ...")
    fno_err = {}                     # nu -> (l2, linf) per-sample arrays
    for nu in NUS:
        l2, linf = evaluate_fno(fnos[nu], u0_test, refs[nu][test_idx])
        fno_err[nu] = (l2, linf)
        print(f"  FNO nu={nu:g}: rel-L2 = {l2.mean():.4e} "
              f"rel-Linf = {linf.mean():.4e}")

    # ---------- FDM baselines ---------------------------------------------------
    print("FDM baselines (Lax-Friedrichs + TVD, N = 64) ...")
    fdm_err = {}
    fdm_sol_nu = {}
    # nu = 0.01: reuse the Section 4.1.3 FDM solutions
    fdm_sol01 = np.loadtxt(os.path.join(DATA_DIR, "4.1_fdm_solutions_final.csv"),
                           delimiter=",", skiprows=1)
    fdm_sol_nu[0.01] = fdm_sol01
    ref01_64 = refs[0.01][:, ::step]
    l2, linf = rel_l2_linf_batch(fdm_sol01[test_idx], ref01_64[test_idx])
    fdm_err[0.01] = (l2, linf)
    print(f"  FDM nu=0.01 (reused): rel-L2 = {l2.mean():.4e} "
          f"rel-Linf = {linf.mean():.4e}")

    for nu in (0.1, 0.001):
        sol, refg, dt, n_steps = fdm_solve_for_nu(u0_all, refs[nu], nu,
                                                  train_idx, test_idx)
        fdm_sol_nu[nu] = sol
        l2, linf = rel_l2_linf_batch(sol[test_idx], refg[test_idx])
        fdm_err[nu] = (l2, linf)
        print(f"  FDM nu={nu:g}: dt = {dt:.4e}, {n_steps} steps, "
              f"rel-L2 = {l2.mean():.4e}, rel-Linf = {linf.mean():.4e}")

    # ---------- summaries -------------------------------------------------------
    summary = []
    for nu in NUS:
        for method, err in (("FNO", fno_err[nu]), ("FDM", fdm_err[nu])):
            l2, linf = err
            lo2, hi2 = bootstrap_ci(l2)
            lof, hif = bootstrap_ci(linf)
            summary.append({
                "nu": nu, "method": method,
                "mean_rel_l2": l2.mean(), "ci_low_l2": lo2, "ci_high_l2": hi2,
                "mean_rel_linf": linf.mean(), "ci_low_linf": lof,
                "ci_high_linf": hif,
            })
            print(f"  [{method} nu={nu:g}] L2 = {l2.mean():.4e} "
                  f"[{lo2:.4e}, {hi2:.4e}]  Linf = {linf.mean():.4e} "
                  f"[{lof:.4e}, {hif:.4e}]")

    # FNO-to-FDM error ratios
    print("-" * 78)
    for nu in NUS:
        ratio = (fno_err[nu][0].mean() / fdm_err[nu][0].mean())
        print(f"  nu={nu:g}: FNO/FDM rel-L2 ratio = {ratio:.3f}")

    # ---------- save CSVs --------------------------------------------------------
    with open(os.path.join(DATA_DIR, "4.3_error_metrics.csv"), "w") as fh:
        fh.write("sample_index,split,nu,method,rel_l2,rel_linf\n")
        for k, s in enumerate(test_idx):
            for nu in NUS:
                fh.write(f"{s},test,{nu:g},FNO,{fno_err[nu][0][k]:.8e},"
                         f"{fno_err[nu][1][k]:.8e}\n")
                fh.write(f"{s},test,{nu:g},FDM,{fdm_err[nu][0][k]:.8e},"
                         f"{fdm_err[nu][1][k]:.8e}\n")
    print(f"Saved: {os.path.join(DATA_DIR, '4.3_error_metrics.csv')}")

    # summary CSV
    with open(os.path.join(DATA_DIR, "4.3_summary.csv"), "w") as fh:
        fh.write("nu,method,mean_rel_l2,ci_low_l2,ci_high_l2,"
                 "mean_rel_linf,ci_low_linf,ci_high_linf\n")
        for r in summary:
            fh.write(f"{r['nu']:g},{r['method']},{r['mean_rel_l2']:.8e},"
                     f"{r['ci_low_l2']:.8e},{r['ci_high_l2']:.8e},"
                     f"{r['mean_rel_linf']:.8e},{r['ci_low_linf']:.8e},"
                     f"{r['ci_high_linf']:.8e}\n")
    print(f"Saved: {os.path.join(DATA_DIR, '4.3_summary.csv')}")

    # parameters CSV
    with open(os.path.join(DATA_DIR, "4.3_parameters.csv"), "w") as fh:
        fh.write("parameter,value\n")
        for key, val in [
            ("equation", "u_t + u u_x = nu*u_xx, x in [0,1), periodic BC"),
            ("viscosities", "0.1, 0.01, 0.001"),
            ("N_GRID", N_GRID), ("N_REF", N_REF),
            ("N_TRAIN", N_TRAIN), ("N_TEST", N_TEST), ("seed", SEED),
            ("fno_arch", "L=4, k_max=16, d_v=64, GELU"),
            ("training", f"Adam lr={LR}, cosine, {EPOCHS} epochs, batch {BATCH_SIZE}"),
            ("fno_nu0p01", "reused from Section 4.2 (4.2_fno_weights.pt)"),
            ("fdm", "Lax-Friedrichs + TVD (van Leer), N=64, RK4"),
            ("fdm_nu0p01", "reused from Section 4.1.3 (4.1_fdm_solutions_final.csv)"),
            ("reference", "Fourier pseudo-spectral + IF-RK4, N=2048, "
                          "validated vs Cole-Hopf"),
            ("bootstrap", f"{BOOT_ITER} resamples, 95% CI"),
        ]:
            fh.write(f"{key},{val}\n")

    # ---------- figures ----------------------------------------------------------
    plot_viscosity_sensitivity(summary, os.path.join(
        FIG_DIR, "4.3_viscosity_sensitivity.png"))

    # select the two test samples with the sharpest features at nu = 0.001
    dxr = 1.0 / N_REF
    sharpness = np.array([np.abs(np.gradient(refs[0.001][s], dxr)).max()
                          for s in test_idx])
    sharp_samples = [int(test_idx[i]) for i in
                     np.argsort(sharpness)[::-1][:2]]
    print(f"Sharpest nu=0.001 test samples for the snapshot figure: "
          f"{sharp_samples}")
    plot_shock_snapshots(u0_all, refs[0.001], fnos[0.001],
                         fdm_sol_nu[0.001], 0.001, sharp_samples,
                         os.path.join(FIG_DIR, "4.3_shock_snapshots.png"))

    # ---------- README ------------------------------------------------------------
    ratios = {nu: fno_err[nu][0].mean() / fdm_err[nu][0].mean() for nu in NUS}
    write_readme(summary, ratios, fnos)

    print("=" * 78)
    print(f"Done. Total wall-clock time: {time.time() - t_start:.1f} s")
    print("=" * 78)


