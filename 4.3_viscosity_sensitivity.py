def rel_l2_linf_batch(pred, ref):
    """Per-sample relative L2 and L-infinity errors, shapes (n, N)."""
    l2 = np.linalg.norm(pred - ref, axis=1) / np.linalg.norm(ref, axis=1)
    linf = np.max(np.abs(pred - ref), axis=1) / np.max(np.abs(ref), axis=1)
    return l2, linf


def evaluate_fno(fno, u0_test, ref_test, grid=N_GRID):
    """Zero-shot-free (same-resolution) FNO evaluation on the test set."""
    step = N_REF // grid
    X = torch.tensor(u0_test[:, ::step], dtype=torch.float32)
    y = ref_test[:, ::step]
    fno.eval()
    with torch.no_grad():
        pred = fno(X).numpy()
    return rel_l2_linf_batch(pred, y)


def _van_leer_limiter(du_b, du_f):
    """Van Leer TVD limiter (works on (B, N) arrays, axis = -1)."""
    same_sign = du_b * du_f > 0.0
    with np.errstate(divide="ignore", invalid="ignore"):
        phi = np.where(same_sign, 2.0 * du_b / (du_b + du_f + 1e-30), 0.0)
    return phi


def _fdm_rhs(u, nu, dx, dx2):
    """FDM RHS (Lax-Friedrichs flux + van Leer TVD) vectorized over samples.

    u : (B, N) batch of point values on the periodic grid.
    """
    du_f = np.roll(u, -1, axis=-1) - u              # u[j+1] - u[j]
    du_b = u - np.roll(u, 1, axis=-1)               # u[j] - u[j-1]
    u_l = u + 0.5 * _van_leer_limiter(du_b, du_f) * du_f
    u_r = np.roll(u, -1, axis=-1) - 0.5 * _van_leer_limiter(
        du_f, np.roll(du_f, -1, axis=-1)) * np.roll(du_f, -1, axis=-1)
    c = np.maximum(np.abs(u_l), np.abs(u_r))
    flux = 0.5 * (0.5 * u_l**2 + 0.5 * u_r**2) - 0.5 * c * (u_r - u_l)
    dudt = (-(flux - np.roll(flux, 1, axis=-1)) / dx
            + nu * (np.roll(u, -1, axis=-1) - 2.0 * u
                    + np.roll(u, 1, axis=-1)) / dx2)
    return dudt


def fdm_solve_batched(u0_batch, nu, dx, dt, n_steps):
    """Explicit RK4 FDM solve for a batch of initial conditions."""
    dx2 = dx * dx
    u = np.array(u0_batch, dtype=float)
    for _ in range(n_steps):
        k1 = _fdm_rhs(u, nu, dx, dx2)
        k2 = _fdm_rhs(u + 0.5 * dt * k1, nu, dx, dx2)
        k3 = _fdm_rhs(u + 0.5 * dt * k2, nu, dx, dx2)
        k4 = _fdm_rhs(u + dt * k3, nu, dx, dx2)
        u = u + (dt / 6.0) * (k1 + 2.0 * k2 + 2.0 * k3 + k4)
    return u


def fdm_solve_for_nu(u0_all, ref_all, nu, train_idx, test_idx):
    """FDM baseline (N = 64) for all samples at viscosity nu (batched).

    The solution is written to a checkpoint CSV so that re-runs reuse it.
    Returns the (1000, N) FDM solution and the (1000, N) reference on the
    same grid.
    """
    tag = "nu0p1" if nu == 0.1 else "nu0p001"
    sol_path = os.path.join(DATA_DIR, f"4.3_fdm_solutions_{tag}.csv")
    refg = ref_all[:, ::N_REF // N_GRID]
    if os.path.exists(sol_path):
        sol = np.loadtxt(sol_path, delimiter=",", skiprows=1)
        print(f"  FDM nu={nu:g}: loaded from {sol_path}")
        return sol, refg, float("nan"), 0

    dx = 1.0 / N_GRID
    u0g = u0_all[:, ::N_REF // N_GRID]
    umax = np.abs(u0g).max()
    dt = m41.fdm_cfl_dt(dx, nu, umax)
    n_steps = max(int(np.ceil(m41.T_MAX / dt)), FDM_MIN_STEPS)
    dt = m41.T_MAX / n_steps
    sol = fdm_solve_batched(u0g, nu, dx, dt, n_steps)
    np.savetxt(sol_path, sol, delimiter=",", fmt="%.8e",
               header=",".join(f"{i / N_GRID:.6f}" for i in range(N_GRID)),
               comments="")
    print(f"  FDM nu={nu:g}: dt = {dt:.4e}, {n_steps} steps "
          f"(batched), saved to {sol_path}")
    return sol, refg, dt, n_steps


