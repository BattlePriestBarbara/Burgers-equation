    train_idx = np.array([i for i, ln in enumerate(lines)
                          if ln.split(",")[1] == "train"])
    test_idx = np.array([i for i, ln in enumerate(lines)
                         if ln.split(",")[1] == "test"])

    refs = {}
    # nu = 0.01: from Section 4.1.1 (train/test files)
