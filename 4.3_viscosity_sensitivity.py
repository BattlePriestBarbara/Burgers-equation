def plot_viscosity_sensitivity(summary, path):
    """Rel L2 error vs viscosity for FNO and FDM (log-x axis)."""
    fig, ax = plt.subplots(figsize=(7.5, 5.2))
    for method, color, marker in (("FNO", "#1f77b4", "o"),
                                  ("FDM", "#d62728", "s")):
        sub = sorted([r for r in summary if r["method"] == method],
                     key=lambda r: r["nu"])
        x = [r["nu"] for r in sub]
        y = [r["mean_rel_l2"] for r in sub]
        lo = [r["ci_low_l2"] for r in sub]
        hi = [r["ci_high_l2"] for r in sub]
        ax.plot(x, y, marker + "-", lw=1.8, color=color,
                label=f"{method} (N={N_GRID})")
        ax.fill_between(x, lo, hi, color=color, alpha=0.2,
                        label=f"{method} 95% CI")
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xticks(NUS)
    ax.set_xticklabels(["$10^{-1}$", "$10^{-2}$", "$10^{-3}$"])
    ax.set_xlabel(r"Viscosity  $\nu$")
    ax.set_ylabel("Mean relative L2 error (200 test samples)")
    ax.set_title("Viscosity Sensitivity: FNO Accuracy Degradation\n"
                 "as the Shock Gets Sharper (Burgers, N = 64)")
    ax.grid(True, alpha=0.3, which="both")
    ax.legend(fontsize=9)
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def plot_shock_snapshots(u0_test, ref_test, fno, fdm_sol, nu, sample_ids, path):
    """nu = 0.001 snapshots: reference vs FNO (zero-shot @2048) vs FDM.

    Top row: full N = 2048 view (FNO evaluated at N = 2048 shows the
    smoothing of the shock).  Bottom row: zoom on the steepest region.
    """
    x_ref = np.arange(N_REF) / N_REF
    x64 = (np.arange(N_GRID) + 0.0) / N_GRID
    fig, axes = plt.subplots(2, len(sample_ids), figsize=(4.6 * len(sample_ids), 6.0))
    with torch.no_grad():
        for j, s in enumerate(sample_ids):
            X = torch.tensor(u0_test[s], dtype=torch.float32).unsqueeze(0)
            pred_fno = fno(X).numpy()[0]                # zero-shot at N=2048
            ref = ref_test[s]

            # top row: full field at N = 2048
            ax = axes[0, j]
            ax.plot(x_ref, ref, lw=1.0, color="black", label="Reference (N=2048)")
            ax.plot(x_ref, pred_fno, lw=1.0, color="#1f77b4", label="FNO (N=2048, zero-shot)")
            ax.plot(x64, fdm_sol[s], "o", ms=2.5, color="#d62728", label="FDM (N=64)")
            ax.set_title(f"Test sample {s}  ($\\nu$ = {nu:g})")
            ax.grid(True, alpha=0.3)
            if j == 0:
                ax.set_ylabel(r"$u(x,T)$")
            ax.legend(fontsize=7)

            # bottom row: zoom on the region of largest reference gradient
            grad = np.abs(np.gradient(ref))
            imax = int(np.argmax(grad))
            x0, x1 = max(0.0, x_ref[imax] - 0.12), min(1.0, x_ref[imax] + 0.12)
            m = (x_ref >= x0) & (x_ref <= x1)
            ax = axes[1, j]
            ax.plot(x_ref[m], ref[m], lw=1.3, color="black")
            ax.plot(x_ref[m], pred_fno[m], lw=1.3, color="#1f77b4")
            ax.plot(x64[(x64 >= x0) & (x64 <= x1)],
                    fdm_sol[s][(x64 >= x0) & (x64 <= x1)], "o", ms=3.0, color="#d62728")
            ax.set_xlim(x0, x1)
            ax.grid(True, alpha=0.3)
            if j == 0:
                ax.set_ylabel(r"$u(x,T)$")
            ax.set_xlabel("$x$")
    fig.suptitle("Sharp-Feature (Near-Shock) Capture at $\\nu = 0.001$: "
                 "the FNO Smoothes the Steep Gradients "
                 "(bandwidth-limited to $k_{max} = 16$)")
    fig.tight_layout(rect=[0, 0, 1, 0.95])
    fig.savefig(path, dpi=150)
    plt.close(fig)


